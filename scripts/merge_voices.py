import os
import sys
import argparse
import torch

# PyTorch 2.6+ compatibility for StyleTTS2 checkpoint deserialization
_orig_load = torch.load
torch.load = lambda *args, **kwargs: _orig_load(
    *args, **{**({"weights_only": False} if "weights_only" not in kwargs else {}), **kwargs}
)

import soundfile as sf
from styletts2 import tts

REPO_DIR = os.path.abspath(os.path.join(os.path.dirname(__file__), ".."))
CHECKPOINT_PATH = os.path.join(REPO_DIR, "models", "epochs_2nd_00020.pth")
CONFIG_PATH = os.path.join(REPO_DIR, "models", "config.yml")

# Configure eSpeak NG path and phonemizer library bindings
candidate_paths = [
    r"C:\Program Files\eSpeak NG\libespeak-ng.dll",
    r"C:\Program Files (x86)\eSpeak NG\libespeak-ng.dll",
    os.path.join(REPO_DIR, "espeak-ng", "libespeak-ng.dll"),
]

for candidate in candidate_paths:
    if os.path.exists(candidate):
        os.environ["PHONEMIZER_ESPEAK_PATH"] = candidate
        os.environ["PHONEMIZER_ESPEAK_LIBRARY"] = candidate
        dll_dir = os.path.dirname(candidate)
        if dll_dir not in os.environ.get("PATH", ""):
            os.environ["PATH"] = dll_dir + os.pathsep + os.environ.get("PATH", "")
        if "espeak-ng" in dll_dir.lower():
            os.environ["ESPEAK_DATA_PATH"] = dll_dir
        try:
            from phonemizer.backend.espeak.wrapper import EspeakWrapper
            EspeakWrapper.set_library(candidate)
        except Exception:
            pass
        print(f"[*] Configured eSpeak library: {candidate}")
        break

def blend_style_vectors(s1: torch.Tensor, s2: torch.Tensor, alpha: float = 0.5) -> torch.Tensor:
    """
    Interpolates two style embedding vectors.
    alpha = 1.0 -> 100% Voice A
    alpha = 0.0 -> 100% Voice B
    alpha = 0.5 -> 50/50 blend
    """
    return alpha * s1 + (1.0 - alpha) * s2

def main():
    parser = argparse.ArgumentParser(description="Merge two voice samples into a unified StyleTTS-2 identity.")
    parser.add_argument("--voice-a", type=str, default=os.path.join(REPO_DIR, "input", "voice_a.wav"),
                        help="Path to Voice A reference audio file (.wav)")
    parser.add_argument("--voice-b", type=str, default=os.path.join(REPO_DIR, "input", "voice_b.wav"),
                        help="Path to Voice B reference audio file (.wav)")
    parser.add_argument("--ratio", type=float, default=0.5,
                        help="Blend ratio: 1.0 is 100%% Voice A, 0.0 is 100%% Voice B, 0.5 is equal blend")
    parser.add_argument("--output-pt", type=str, default=os.path.join(REPO_DIR, "output", "merged_identity.pt"),
                        help="Output path for the saved frozen style embedding (.pt)")
    parser.add_argument("--output-wav", type=str, default=os.path.join(REPO_DIR, "output", "test_blend.wav"),
                        help="Output path for synthesis test audio (.wav)")
    parser.add_argument("--test-text", type=str,
                        default="This is a custom synthetic voice generated by blending two distinct vocal identities in StyleTTS 2.",
                        help="Sample text line to synthesize as verification")
    args = parser.parse_args()

    voice_a_path = os.path.abspath(args.voice_a)
    voice_b_path = os.path.abspath(args.voice_b)
    output_voice_pt = os.path.abspath(args.output_pt)
    test_output_wav = os.path.abspath(args.output_wav)

    os.makedirs(os.path.dirname(output_voice_pt), exist_ok=True)
    os.makedirs(os.path.dirname(test_output_wav), exist_ok=True)

    if not os.path.exists(voice_a_path):
        print(f"[!] Error: Voice A not found at: {voice_a_path}")
        sys.exit(1)
    if not os.path.exists(voice_b_path):
        print(f"[!] Error: Voice B not found at: {voice_b_path}")
        sys.exit(1)

    print("========================================================")
    print("           StyleTTS-2 Voice Identity Merger             ")
    print("========================================================")
    print(f" Voice A : {voice_a_path}")
    print(f" Voice B : {voice_b_path}")
    print(f" Ratio   : {args.ratio:.2f} Voice A + {1.0 - args.ratio:.2f} Voice B")
    print(f" Output  : {output_voice_pt}")
    print("========================================================")

    device = "cuda" if torch.cuda.is_available() else "cpu"
    print(f"[*] Running on device: {device.upper()}")

    print("[*] Initializing StyleTTS-2 engine...")
    if os.path.exists(CHECKPOINT_PATH) and os.path.exists(CONFIG_PATH):
        print(f"[*] Loading local checkpoint: {CHECKPOINT_PATH}")
        engine = tts.StyleTTS2(model_checkpoint_path=CHECKPOINT_PATH, config_path=CONFIG_PATH)
    else:
        print("[*] Local checkpoint not found. Falling back to default download...")
        engine = tts.StyleTTS2()

    print("[*] Extracting acoustic style latents...")
    s_a = engine.compute_style(voice_a_path)
    s_b = engine.compute_style(voice_b_path)

    print(f"[*] Interpolating style space with ratio {args.ratio:.2f} : {1.0 - args.ratio:.2f}...")
    s_merged = blend_style_vectors(s_a, s_b, alpha=args.ratio)

    # Save frozen embedding tensor
    torch.save(s_merged, output_voice_pt)
    print(f"[+] Saved merged style identity to: {output_voice_pt}")

    # Synthesize test line
    print(f"[*] Synthesizing verification sample...")
    audio_array = engine.inference(
        text=args.test_text,
        ref_s=s_merged,
        alpha=0.3,
        beta=0.7,
        diffusion_steps=10,
        embedding_scale=1.0
    )

    sf.write(test_output_wav, audio_array, samplerate=24000)
    print(f"[+] Test audio successfully exported to: {test_output_wav}\n")
    print("[SUCCESS] Voice merger complete!")

if __name__ == "__main__":
    main()
